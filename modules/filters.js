// ===== 1. ТЕКУЩИЙ ФИЛЬТР =====
// По умолчанию показываем всех клиентов
let currentFilter = "all";

// ===== 2. УСТАНОВИТЬ ФИЛЬТР =====
export function setFilter(filter) {
  currentFilter = filter; // сохраняем новый фильтр
}

// ===== 3. ПОЛУЧИТЬ ТЕКУЩИЙ ФИЛЬТР =====
export function getFilter() {
  return currentFilter; // возвращаем текущий фильтр
}
